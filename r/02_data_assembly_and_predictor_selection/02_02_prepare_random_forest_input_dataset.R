# ==============================================================================
# Script: 02_02_prepare_random_forest_input_dataset.R
# Original file: 01_datenvorbereitung_rolling_av_merge.R
#
# Purpose:
#   Combines the annual climate master datasets, derives calendar variables and
#   three-day rolling exposure metrics, merges district-level heat-warning data,
#   applies the prespecified missing-data handling steps, and creates the input
#   dataset used for Random Forest model development.
#
# Inputs:
#   - Annual Climate_Master_Daily_<year>.csv files
#   - Annual district-level heat-warning Excel files containing one row per date
#     and one column per AGS
#
# Outputs:
#   - RFM_Input_Data.rds
#   - RFM_Input_Data.csv
#
# Derived variables:
#   - Calendar year, month, day, day of year, and day of week
#   - Three-day rolling means for selected temperature, apparent-temperature,
#     radiation, and sunshine-duration variables
#
# Spatial unit:
#   Harmonized German administrative districts identified by AGS
#
# Temporal coverage:
#   2000–2022
#
# Required packages:
#   readxl, dplyr, tidyr, zoo, tidyverse, data.table
#
# Dependencies:
#   Requires the annual climate master datasets generated by
#   02_01_assemble_annual_climate_exposure_data.R and the prepared annual
#   district-level heat-warning tables.
#
# Repository note:
#   Paths are project-relative and assume that the working directory is set to
#   the repository root. Only path strings and explanatory comments were
#   standardized for repository publication.
# ==============================================================================

# Load required packages

library(readxl)
library(dplyr)
library(tidyr)
library(zoo)       
library(tidyverse)
library(data.table) 

# 1. Import assembled climate data

path_climate <- "data/intermediate/data_assembly/annual_climate_data"

climate_files <- list.files(
  path = path_climate, 
  pattern = "\\.csv$",  
  full.names = TRUE     
)

cat("Gefundene Dateien:", length(climate_files), "\n")

# Read and row-bind the annual climate files

data.cl <- bind_rows(lapply(climate_files, function(file) {
  read_delim(file, delim = ",", show_col_types = FALSE)
}))

# Inspect the imported dataset
cat("Import abgeschlossen. Gesamtzeilen:", nrow(data.cl), "\n")
head(data.cl)

# 2. Calculate three-day rolling exposure metrics

data.cl <- data.cl %>%
  mutate(
    year = as.integer(format(Datum, "%Y")),
    month = as.integer(format(Datum, "%m")),
    day = as.integer(format(Datum, "%d")),
    yday = as.POSIXlt(Datum)$yday + 1,
    dow = as.factor(weekdays(Datum)),
    AGS = as.character(AGS) 
  )

data.cl <- data.cl %>%
  arrange(AGS, Datum) %>% 
  group_by(AGS) %>% 
  
  mutate(
    D3_min = round(rollmean(Temp_Min, k = 3, fill = NA, align = 'right'), 1),
    D3_max = round(rollmean(Temp_Max, k = 3, fill = NA, align = 'right'), 1),
    D3_AT_Max = round(rollmean(AT_Max, k = 3, fill = NA, align = 'right'), 1),
    D3_AT_Mean = round(rollmean(AT_Mean, k = 3, fill = NA, align = 'right'), 1),
    D3_Rad_Max = round(rollmean(Radiation_Max, k = 3, fill = NA, align = 'right'), 1),
    D3_Sun_Hours = round(rollmean(Sunshine_Hours, k = 3, fill = NA, align = 'right'), 1)
    
  ) %>%
  ungroup()

# Inspect the resulting column names
print(colnames(data.cl))

# 3. Import annual district-level heat-warning data

AGS_HW_path <- "data/intermediate/exposure/heat_alerts/annual_district_tables"

file_list <- list.files(
  path = AGS_HW_path,
  pattern = "^AGS_Hitzewarnungen.*\\.(xlsx|xls)$",
  full.names = TRUE
)

read_hw_data <- function(file) {
  data <- read_excel(file)
  
  year_str <- gsub(".*(\\d{4})\\.(xlsx|xls)$", "\\1", basename(file))
  
  data_long <- data %>%
    pivot_longer(
      cols = -Datum, 
      names_to = "AGS", 
      values_to = "HW_Status" 
    ) %>%
    mutate(
      AGS = as.character(AGS), 
      # Retain the original date-column name
      Datum = as.Date(Datum), 
      year = as.integer(year_str)
    ) 
  # The date column is retained for the subsequent merge
  
  return(data_long)
}

# Combine the annual heat-warning files
hw_ags_list <- lapply(file_list, read_hw_data)
hw_ags_combined <- bind_rows(hw_ags_list)   

# 4. Merge climate and heat-warning data
data.cl_final <- left_join(data.cl, hw_ags_combined, by = c("Datum", "AGS", "year")) 

# 5. Summarize missing heat-warning status by year
cat("Verteilung der NAs pro Jahr:\n")
data.cl_final %>%
  filter(is.na(HW_Status)) %>%
  count(year) %>%
  print()
# Missing heat-warning status values are expected before 2005 because official warnings were not yet available

# Inspect the assembled dataset
head(data.cl_final)
str(data.cl_final)

# Missing-data handling and data cleaning

# CHECK
print("Anzahl NAs pro Spalte vor Bereinigung:")
print(colSums(is.na(data.cl_final)))

# Replace missing population-weighted estimates with district-level unweighted means

data.cl_final <- data.cl_final %>%
  mutate(
    # Beispiel für Temperatur:
    # Wenn temp_pop_w fehlt, nimm Temp_Mean
    temp_pop_w = coalesce(temp_pop_w, Temp_Mean),
    wind_pop_w = coalesce(wind_pop_w, Wind_Mean),
    dewpoint_pop_w = coalesce(dewpoint_pop_w, Dew_Mean)
  )

# Remove rows with missing three-day rolling metrics
data.cl_final <- data.cl_final %>% 
  drop_na(D3_min, D3_max, D3_AT_Max, D3_AT_Mean, D3_Rad_Max, D3_Sun_Hours) 

# Verify missingness after data cleaning
cat("Zeilen gesamt:", nrow(data.cl_final), "\n")
cat("NAs in D3_min (sollte 0 sein):", sum(is.na(data.cl_final$D3_min)), "\n")
cat("NAs in D3_max (sollte 0 sein):", sum(is.na(data.cl_final$D3_max)), "\n")
cat("NAs in D3_AT_Max (sollte 0 sein):", sum(is.na(data.cl_final$D3_AT_Max)), "\n")
cat("NAs in D3_Rad_Max (sollte 0 sein):", sum(is.na(data.cl_final$D3_Rad_Max)), "\n")
cat("NAs in D3_Sun_Hours (sollte 0 sein):", sum(is.na(data.cl_final$D3_Sun_Hours)), "\n")

cat("NAs in HW_Status (darf > 0 sein für 2000-2004):", sum(is.na(data.cl_final$HW_Status)), "\n")

# Report the remaining number of observations
cat("Verbleibende Zeilen:", nrow(data.cl_final), "\n")

# Speicher bereinigen
rm(data.cl, hw_ags_combined, file_list, hw_ags_list)
gc()

# Save the Random Forest input dataset
write_rds(
  data.cl_final,
  "data/processed/random_forest_input/RFM_Input_Data.rds"
)
write.csv(
  data.cl_final,
  "data/processed/random_forest_input/RFM_Input_Data.csv"
)
