cat("### START: BERECHNUNG FÜR THRESHOLD 0.7 ###\n")

# 1. Zukunft (mit Validierung) - 0.7
evaluate_and_save(rf_model, test_future, "2011-2022", threshold = 0.7)

# 2. Vergangenheit (Simulation) - 0.7
simulate_only(rf_model, test_historic, "2000-2004", threshold = 0.7)

cat("### START: BERECHNUNG FÜR THRESHOLD 0.8 ###\n")

# 3. Zukunft (mit Validierung) - 0.8
evaluate_and_save(rf_model, test_future, "2011-2022", threshold = 0.8)

# 4. Vergangenheit (Simulation) - 0.8
