# Schnell-Check am Ende in der Konsole
cat("\n--- ZUSAMMENFASSUNG DER ERGEBNISSE ---\n")
for (th in c(0.7, 0.8)) {
  check_threshold_only(rf_model, test_future, threshold = th)
}

